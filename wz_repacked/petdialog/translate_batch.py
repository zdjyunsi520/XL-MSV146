# Helper function to read source file
def read_source(pet_id):
    path = os.path.join(split_dir, f"{pet_id}.xml")
    with open(path, 'r', encoding='utf-8') as f:
        return f.read()

# Helper function to write translated file
def write_translated(pet_id, content):
    path = os.path.join(translated_dir, f"{pet_id}.xml")
    with open(path, 'w', encoding='utf-8') as f:
        f.write(content)

# Process function - translates value attributes using a mapping
def translate_file(pet_id, value_map):
    """Translate a file by replacing value="" content based on a mapping dict"""
    source = read_source(pet_id)

    # Parse all string lines
    lines = source.split('\n')
    result_lines = []

    for line in lines:
        # Match string elements with value attribute
        m = re.match(r'^(\s*<string name=")([^"]+)(" value=")([^"]*)("/>)$', line.rstrip())
        if m:
            prefix1, name, prefix2, old_val, suffix = m.groups()
            key = name
            if key in value_map:
                new_val = value_map[key]
                result_lines.append(f'{prefix1}{name}{prefix2}{new_val}{suffix}')
            else:
                # Keep command trigger values (c1, c2 etc) as-is
                result_lines.append(line.rstrip())
        else:
            result_lines.append(line.rstrip())

    return '\n'.join(result_lines)

