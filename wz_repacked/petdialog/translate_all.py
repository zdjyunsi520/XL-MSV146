def read_source(pet_id):
    path = os.path.join(split_dir, f"{pet_id}.xml")
    with open(path, 'r', encoding='utf-8') as f:
        return f.read()

def write_trans(pet_id, content):
    path = os.path.join(trans_dir, f"{pet_id}.xml")
    with open(path, 'w', encoding='utf-8') as f:
        f.write(content)

def translate_values(source, mapping):
    """Replace value attributes based on name->new_value mapping. Command triggers are kept as-is."""
    def replacer(m):
        full_match = m.group(0)
        name = m.group(1)
        if name in mapping:
            new_val = mapping[name]
            return f'name="{name}" value="{new_val}"'
        return full_match

    return re.sub(r'name="([^"]+)" value="([^"]*)"', replacer, source)

