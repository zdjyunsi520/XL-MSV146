function start(ms) {
if (ms.hasQuest(30000));
    ms.sendDelay(3000);
    
} 
if (ms.hasQuest(30003)) {
    ms.setPlayerAsSpeaker()
    ms.sendNext("嗯..看起来运作正常。回去告诉她出口的情况吧。");
    ms.dispose;
} else {
    ms.dispose();
    ms.setPlayerAsSpeaker();
    ms.sendNext("这雾太浓了！我得保持警觉。谁知道外面潜伏着什么...");
}
    