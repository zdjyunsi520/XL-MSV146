# Apply translations
output = []
matched = 0
for line in lines:
    if '|' not in line:
        output.append(line)
        continue
    idx = line.index('|')
    fname = line[:idx]
    text = line[idx+1:]
    if text in T:
        output.append(f"{fname}|{T[text]}")
        matched += 1
    else:
        output.append(f"{fname}|{text}")

with open(dst, 'w', encoding='utf-8') as f:
    f.write('\n'.join(output) + '\n')

# Verify
with open(dst, 'r', encoding='utf-8') as f:
    out_lines = f.readlines()

# Count translated
translated = 0
for ol in out_lines:
    ol = ol.rstrip()
    if '|' not in ol:
        continue
    t = ol.split('|',1)[1]
    # Check if contains Chinese characters
    has_cn = any('一' <= c <= '鿿' for c in t)
    if has_cn:
        translated += 1

print(f"Output: {len(out_lines)} lines, {matched} dict-matched, {translated} lines with Chinese")
print(f"Remaining: {len(out_lines) - translated} lines still in English")
